/// Тип намерения после семантического разбора русской команды.
///
/// Значения на английском — это внутренние коды; отображение для пользователя
/// задаётся в слое представления или в истории команд.
enum VoiceIntentType {
  /// Не удалось классифицировать намерение.
  unknown,

  /// Показать список / отфильтровать задачи.
  showTasks,

  /// Создать новую задачу.
  createTask,

  /// Отметить задачу выполненной.
  markTaskDone,

  /// Поиск по тексту.
  searchTasks,

  /// Уточнение фильтров (дата, приоритет и т.д.).
  filterTasks,
}
